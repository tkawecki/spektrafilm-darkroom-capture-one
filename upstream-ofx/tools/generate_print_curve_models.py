#!/usr/bin/env python3
"""Extract pinned fitted print models without rewriting legacy native profiles.

The generated model data remains CC BY-SA 4.0, Andrea Volpato; see the
source profiles' metadata and upstream-spektrafilm/SPEKTRAFILM_LICENSE.txt.
"""
import argparse
import hashlib
import json
from pathlib import Path

from ofx_stock_lists import PAPERS

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROFILES = ROOT / "upstream-spektrafilm/src/spektrafilm/data/profiles"
DEFAULT_OUTPUT = ROOT / "upstream-ofx/src/SpektraGeneratedPrintCurveModels.h"


def generate(profiles=DEFAULT_PROFILES):
    lines = [
        "// Generated by upstream-ofx/tools/generate_print_curve_models.py; do not edit.",
        "// Fitted profile data: Copyright (c) 2026 Andrea Volpato, CC BY-SA 4.0.",
        "// https://github.com/andreavolpato/spektrafilm",
        "// License: https://creativecommons.org/licenses/by-sa/4.0/",
        "// Modification: extracted fitted parameters into native C++ arrays.",
        '#pragma once', '#include "SpektraProfileCurves.h"',
        '#include <cstring>', 'namespace spektrafilm {',
        'inline constexpr PrintCurveModel kPrintCurveModels[] = {',
    ]
    for stock in PAPERS:
        path = profiles / f"{stock}.json"
        profile = json.loads(path.read_text(encoding="utf-8"))
        model = profile["data"]["density_curves_model"]
        if model["model_type"] != "cdfs":
            raise ValueError(f"{stock}: unsupported model type")
        lines += [f'  // {path.name}: SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}',
                  '  {' + json.dumps(stock) + ', ' + ('true' if profile['info']['type'] == 'positive' else 'false') + ',']
        for key in ("centers", "amplitudes", "sigmas"):
            rows = model[key]
            if len(rows) != 3 or any(len(row) != 3 for row in rows):
                raise ValueError(f"{stock}: expected three channels and three fitted layers")
            lines.append('    {' + ', '.join('{' + ', '.join(format(v, '.17g') for v in row) + '}' for row in rows) + '},')
        lines.append('  },')
    lines += ['};',
              'inline const PrintCurveModel *paperPrintCurveModel(const char *stock) {',
              '  if (stock) for (const auto &model : kPrintCurveModels)',
              '    if (std::strcmp(stock, model.stock) == 0) return &model;',
              '  return nullptr;', '}', '} // namespace spektrafilm', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profiles', type=Path, default=DEFAULT_PROFILES)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(args.profiles), encoding='utf-8', newline='\n')
    print(f'Wrote {args.output}')
