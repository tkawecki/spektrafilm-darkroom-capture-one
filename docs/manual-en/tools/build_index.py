"""Build docs/manual/assets/search-index.js from the manual's HTML pages.

Indexes each page title, every h2, and every control description (.control > h3) with its panel path.
Anchors use the same slug rule as manual.js, which assigns heading ids at runtime.
Usage: python docs/manual-en/tools/build_index.py
"""
from __future__ import annotations

import json
import re
import unicodedata
from html.parser import HTMLParser
from pathlib import Path

MANUAL = Path(__file__).resolve().parent.parent


def fold(text: str) -> str:
    text = unicodedata.normalize("NFD", text.lower())
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return text.replace("ł", "l")


def slug(text: str) -> str:
    return re.sub(r"^-|-$", "", re.sub(r"[^a-z0-9]+", "-", fold(text)))[:60]


class PageParser(HTMLParser):
    """Collects h1, h2, explicit ids and control blocks (h3 plus .path) from one page."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.title = ""
        self.entries: list[dict[str, str]] = []
        self._capture: str | None = None
        self._buffer: list[str] = []
        self._explicit_id: str | None = None
        self._control_depth = 0
        self._depth = 0
        self._pending_control: dict[str, str] | None = None

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        values = dict(attrs)
        classes = (values.get("class") or "").split()
        self._depth += 1
        if tag == "div" and "control" in classes:
            self._control_depth = self._depth
        if tag in ("h1", "h2") or (tag == "h3" and self._control_depth):
            self._capture, self._buffer, self._explicit_id = tag, [], values.get("id")
        elif tag == "p" and "path" in classes and self._pending_control is not None:
            self._capture, self._buffer = "path", []

    def handle_endtag(self, tag: str) -> None:
        if self._capture and tag == ("p" if self._capture == "path" else self._capture):
            text = " ".join("".join(self._buffer).split())
            if self._capture == "h1":
                self.title = text
            elif self._capture == "h2":
                self.entries.append({"t": text, "a": self._explicit_id or slug(text), "k": ""})
            elif self._capture == "h3":
                self._pending_control = {"t": text, "a": self._explicit_id or slug(text), "k": "", "control": "1"}
                self.entries.append(self._pending_control)
            elif self._capture == "path" and self._pending_control is not None:
                self._pending_control["k"] = text
            self._capture = None
        if tag == "div" and self._control_depth == self._depth:
            self._control_depth = 0
            self._pending_control = None
        self._depth -= 1

    def handle_data(self, data: str) -> None:
        if self._capture:
            self._buffer.append(data)


def build() -> list[dict[str, str]]:
    index: list[dict[str, str]] = []
    for page in sorted(MANUAL.glob("*.html")):
        parser = PageParser()
        parser.feed(page.read_text(encoding="utf-8"))
        chapter = parser.title or page.stem
        index.append({"t": chapter, "u": page.name, "s": "Chapter", "k": ""})
        for entry in parser.entries:
            label = "Funkcja panelu" if entry.get("control") else chapter
            keywords = entry["k"] + (" " + chapter if entry.get("control") else "")
            index.append({"t": entry["t"], "u": f"{page.name}#{entry['a']}", "s": label, "k": keywords.strip()})
    return index


def main() -> None:
    index = build()
    target = MANUAL / "assets" / "search-index.js"
    payload = json.dumps(index, ensure_ascii=False, indent=0)
    target.write_text("/* Generated by docs/manual-en/tools/build_index.py. Do not edit. */\n"
                      f"window.MANUAL_INDEX = {payload};\n", encoding="utf-8")
    print(f"{len(index)} entries -> {target}")


if __name__ == "__main__":
    main()
